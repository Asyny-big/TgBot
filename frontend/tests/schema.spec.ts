// @vitest-environment node
/**
 * `src/api/schema.d.ts` is generated from the backend's OpenAPI document
 * (`npm run api:types`). Left stale, the panel would type-check against an API
 * that no longer exists — so the committed file must be exactly what the
 * generator makes of `backend/openapi.json` today. The backend, in turn,
 * checks that `openapi.json` is the schema its code serves.
 */

import { readFile } from "node:fs/promises";

import openapiTS, { astToString } from "openapi-typescript";
import { describe, expect, it } from "vitest";

const OPENAPI = new URL("../../backend/openapi.json", import.meta.url);
const SCHEMA = new URL("../src/api/schema.d.ts", import.meta.url);
const HEADER = /^\/\*\*\n \* This file was auto-generated by openapi-typescript\.\n \* Do not make direct changes to the file\.\n \*\/\n\n/;

describe("generated API types", () => {
  it("are exactly what the backend's OpenAPI document generates", async () => {
    const generated = astToString(await openapiTS(OPENAPI));
    const committed = (await readFile(SCHEMA, "utf8")).replace(/\r\n/g, "\n");

    expect(HEADER.test(committed)).toBe(true);
    expect(committed.replace(HEADER, ""), "run `npm run api:types`").toBe(generated);
  }, 60_000);
});
