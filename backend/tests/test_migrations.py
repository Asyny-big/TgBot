"""Migration guards.

The schema in ``alembic/versions`` must stay in sync with the ORM metadata: a
model change without a migration is caught here instead of in production.

Rows are seeded with plain SQL naming only the columns that exist at the
revision being tested — the ORM models always describe ``head``, so they cannot
insert into an older schema.
"""

from __future__ import annotations

import asyncio
from typing import TYPE_CHECKING, Any

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import NullPool, text
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import command
from tests.db import alembic_config

if TYPE_CHECKING:
    from collections.abc import Sequence

    from alembic.config import Config

SEED_USER = 990000001
PENDING_CRYPTO_INDEX = "uq_purchases_user_product_pending_crypto"
HEAD = "0008"


def test_migrations_match_the_orm_metadata(migrated_database: str) -> None:
    """``alembic check`` must report no pending autogenerate operations."""
    config = alembic_config(migrated_database)
    try:
        command.check(config)
    except AutogenerateDiffsDetected as diff:  # pragma: no cover - failure path
        pytest.fail(f"ORM metadata and migrations diverged: {diff}")


def test_downgrade_and_upgrade_are_reversible(migrated_database: str) -> None:
    """A full down/up cycle must succeed, including PostgreSQL enum types."""
    config = alembic_config(migrated_database)
    command.downgrade(config, "base")
    command.upgrade(config, "head")
    command.check(config)


# --------------------------------------------------------------------------- #
# Plain SQL helpers                                                           #
# --------------------------------------------------------------------------- #


async def _run(dsn: str, statements: Sequence[str], params: dict[str, Any]) -> list[Any]:
    """Execute statements in one transaction; return each one's first column."""
    engine = create_async_engine(dsn, poolclass=NullPool)
    try:
        async with engine.begin() as connection:
            results = []
            for statement in statements:
                result = await connection.execute(text(statement), params)
                results.append(result.scalar() if result.returns_rows else None)
            return results
    finally:
        await engine.dispose()


def _sql(dsn: str, *statements: str, **params: Any) -> list[Any]:
    return asyncio.run(_run(dsn, statements, params))


def _scalar(dsn: str, statement: str, **params: Any) -> Any:
    return _sql(dsn, statement, **params)[0]


_SEED_BUYER_AND_PRODUCT = (
    "INSERT INTO users (telegram_id) VALUES (:user_id)",
    (
        "INSERT INTO products (id, slug, title, delivery_url, price_stars, price_usdt) "
        "VALUES (gen_random_uuid(), :slug, 'Seeded', 'https://t.me/+seeded', 100, 5.00)"
    ),
)


def _remove_seed(dsn: str) -> None:
    """Delete everything seeded for ``SEED_USER``, whatever the schema revision."""
    has_rewards = _scalar(dsn, "SELECT to_regclass('loyalty_rewards') IS NOT NULL")
    has_daily = _scalar(dsn, "SELECT to_regclass('daily_subscriptions') IS NOT NULL")
    has_runtime = _scalar(dsn, "SELECT to_regclass('daily_outbox') IS NOT NULL")
    has_requests = _scalar(dsn, "SELECT to_regclass('daily_requests') IS NOT NULL")
    requests = [
        "DELETE FROM daily_request_events",
        "DELETE FROM daily_request_items",
        "DELETE FROM daily_requests",
    ]
    runtime = ["DELETE FROM daily_outbox", "DELETE FROM daily_alerts"]
    daily = [
        "DELETE FROM daily_delivery_attempts",
        "DELETE FROM daily_deliveries",
        "DELETE FROM daily_content",
        "DELETE FROM daily_subscriptions",
    ]
    statements = [
        *(requests if has_requests else []),
        *(runtime if has_runtime else []),
        *(daily if has_daily else []),
        *(["DELETE FROM loyalty_rewards WHERE user_id = :user_id"] if has_rewards else []),
        "DELETE FROM purchases WHERE user_id = :user_id",
        "DELETE FROM products WHERE slug LIKE 'seed%'",
        "DELETE FROM users WHERE telegram_id = :user_id",
    ]
    _sql(dsn, *statements, user_id=SEED_USER)


def _version(dsn: str) -> str:
    return str(_scalar(dsn, "SELECT version_num FROM alembic_version"))


def _provider_values(dsn: str) -> list[str]:
    return list(_scalar(dsn, "SELECT enum_range(NULL::payment_provider)::text[]"))


def _purchase_checks(dsn: str) -> set[str]:
    rows = _sql(
        dsn,
        "SELECT array_agg(conname::text) FROM pg_constraint "
        "WHERE conrelid = 'purchases'::regclass AND contype = 'c'",
    )[0]
    return set(rows)


def _index_definition(dsn: str, name: str) -> str | None:
    value = _scalar(dsn, "SELECT indexdef FROM pg_indexes WHERE indexname = :name", name=name)
    return None if value is None else str(value)


