# 0005 — the loyalty schema                                                   #
# --------------------------------------------------------------------------- #


def test_0005_upgrade_adds_the_internal_provider_and_the_loyalty_schema(
    migrated_database: str,
) -> None:
    assert _version(migrated_database) == HEAD
    assert _provider_values(migrated_database) == ["stars", "crypto", "internal"]
    assert _purchase_checks(migrated_database) >= {
        "ck_purchases_amount_matches_provider",
        "ck_purchases_internal_is_loyalty_grant",
        "ck_purchases_loyalty_amount_non_negative",
        "ck_purchases_amount_breakdown_consistent",
    }
    assert "ck_purchases_amount_positive" not in _purchase_checks(migrated_database)
    default = _scalar(
        migrated_database,
        "SELECT column_default FROM information_schema.columns "
        "WHERE table_name = 'purchases' AND column_name = 'loyalty_amount'",
    )
    assert default == "0"
    assert _scalar(migrated_database, "SELECT to_regclass('loyalty_rewards') IS NOT NULL")
    for index in (
        "uq_loyalty_rewards_user_milestone",
        "uq_loyalty_rewards_applied_purchase_id",
        "uq_loyalty_rewards_consumed_purchase_id",
        PENDING_CRYPTO_INDEX,
    ):
        assert _index_definition(migrated_database, index) is not None, index


def _downgrade_then_restore(config: Config, dsn: str) -> dict[str, Any]:
    """Downgrade to 0004, record what the schema looks like, then go back to head."""
    command.downgrade(config, "0004")
    try:
        return {
            "version": _version(dsn),
            "providers": _provider_values(dsn),
            "checks": _purchase_checks(dsn),
            "rewards_table": _scalar(dsn, "SELECT to_regclass('loyalty_rewards') IS NOT NULL"),
            "loyalty_column": _scalar(
                dsn,
                "SELECT count(*) FROM information_schema.columns "
                "WHERE table_name = 'purchases' AND column_name = 'loyalty_amount'",
            ),
            "pending_crypto_index": _index_definition(dsn, PENDING_CRYPTO_INDEX),
            "reward_types": _scalar(
                dsn,
                "SELECT count(*) FROM pg_type "
                "WHERE typname IN ('loyalty_reward_kind', 'loyalty_reward_status')",
            ),
        }
    finally:
        command.upgrade(config, "head")


def test_0005_downgrade_on_an_empty_database_restores_0004_exactly(
    migrated_database: str,
) -> None:
    config = alembic_config(migrated_database)
    index_before = _index_definition(migrated_database, PENDING_CRYPTO_INDEX)

    after = _downgrade_then_restore(config, migrated_database)

    assert after["version"] == "0004"
    assert after["providers"] == ["stars", "crypto"]
    assert "ck_purchases_amount_positive" in after["checks"]
    assert not after["checks"] & {
        "ck_purchases_amount_matches_provider",
        "ck_purchases_internal_is_loyalty_grant",
        "ck_purchases_loyalty_amount_non_negative",
    }
    assert after["rewards_table"] is False
    assert after["loyalty_column"] == 0
    assert after["reward_types"] == 0
    # Migration 0004's partial index is rebuilt exactly as it was.
    assert after["pending_crypto_index"] == index_before
    assert after["pending_crypto_index"] is not None
    assert (
        "WHERE ((status = 'pending'::purchase_status) AND (provider = 'crypto'"
        in (after["pending_crypto_index"])
    )
    # …and the round trip leaves the schema matching the models again.
    assert _version(migrated_database) == HEAD
    command.check(config)


def test_0005_downgrade_drops_rewards_that_were_never_used(migrated_database: str) -> None:
    """An available reward holds no history: it is recorded again when used."""
    config = alembic_config(migrated_database)
    _sql(
        migrated_database,
        *_SEED_BUYER_AND_PRODUCT,
        "INSERT INTO loyalty_rewards (id, user_id, milestone, kind) "
        "VALUES (gen_random_uuid(), :user_id, 5, 'discount_50_percent')",
        user_id=SEED_USER,
        slug="seedavailable",
    )
    try:
        after = _downgrade_then_restore(config, migrated_database)
        assert after["version"] == "0004"
        assert after["rewards_table"] is False
    finally:
        _remove_seed(migrated_database)


