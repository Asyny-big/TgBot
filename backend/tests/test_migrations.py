# 0004 — one live crypto checkout per buyer and product                       #
# --------------------------------------------------------------------------- #


def test_0004_refuses_to_run_over_duplicate_pending_crypto_checkouts(
    migrated_database: str,
) -> None:
    """The index migration never resolves duplicates itself: it waits for them to expire."""
    config = alembic_config(migrated_database)
    command.downgrade(config, "0003")
    _sql(
        migrated_database,
        *_SEED_BUYER_AND_PRODUCT,
        *(
            (
                "INSERT INTO purchases (id, user_id, product_id, provider, amount, currency, "
                "external_id) VALUES (gen_random_uuid(), :user_id, "
                "(SELECT id FROM products WHERE slug = :slug), 'crypto', 5.00, 'USDT', "
                ":first_invoice)"
            ),
            (
                "INSERT INTO purchases (id, user_id, product_id, provider, amount, currency, "
                "external_id) VALUES (gen_random_uuid(), :user_id, "
                "(SELECT id FROM products WHERE slug = :slug), 'crypto', 5.00, 'USDT', "
                ":second_invoice)"
            ),
        ),
        user_id=SEED_USER,
        slug="seeddup",
        first_invoice="dup-1",
        second_invoice="dup-2",
    )
    try:
        with pytest.raises(RuntimeError, match="more than one pending crypto purchase"):
            command.upgrade(config, "head")
        # Nothing was rewritten by the refused upgrade: both rows are still pending.
        pending = _scalar(
            migrated_database,
            "SELECT count(*) FROM purchases WHERE user_id = :user_id AND status = 'pending'",
            user_id=SEED_USER,
        )
        assert pending == 2
    finally:
        _remove_seed(migrated_database)
        command.upgrade(config, "head")
    command.check(config)


