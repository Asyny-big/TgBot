"""Migration guards.

The schema in ``alembic/versions`` must stay in sync with the ORM metadata: a
model change without a migration is caught here instead of in production.
"""

from __future__ import annotations

import asyncio
from decimal import Decimal
from typing import TYPE_CHECKING
from uuid import uuid4

import pytest
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import NullPool, text
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from alembic import command
from app.domain.enums import Currency, PaymentProvider
from app.infrastructure.db.models import ProductModel, PurchaseModel, UserModel
from tests.db import alembic_config

if TYPE_CHECKING:
    from uuid import UUID


def test_migrations_match_the_orm_metadata(migrated_database: str) -> None:
    """``alembic check`` must report no pending autogenerate operations."""
    config = alembic_config(migrated_database)
    try:
        command.check(config)
    except AutogenerateDiffsDetected as diff:  # pragma: no cover - failure path
        pytest.fail(f"ORM metadata and migrations diverged: {diff}")


def test_downgrade_and_upgrade_are_reversible(migrated_database: str) -> None:
    """A full down/up cycle must succeed, including PostgreSQL enum types."""
    config = alembic_config(migrated_database)
    command.downgrade(config, "base")
    command.upgrade(config, "head")
    command.check(config)


async def _seed_duplicate_pending_checkouts(dsn: str) -> tuple[int, UUID]:
    """Two pending crypto purchases of one product by one buyer, as before 0004."""
    engine = create_async_engine(dsn, poolclass=NullPool)
    try:
        async with AsyncSession(engine) as session, session.begin():
            buyer = UserModel(telegram_id=990000001)
            product = ProductModel(
                slug=f"dup{uuid4().hex[:8]}",
                title="Duplicated",
                delivery_url="https://t.me/+dup",
                price_usdt=Decimal("5.00"),
            )
            session.add_all([buyer, product])
            await session.flush()
            session.add_all(
                PurchaseModel(
                    user_id=buyer.telegram_id,
                    product_id=product.id,
                    provider=PaymentProvider.CRYPTO,
                    amount=Decimal("5.00"),
                    currency=Currency.USDT,
                    external_id=external_id,
                )
                for external_id in ("dup-1", "dup-2")
            )
            return buyer.telegram_id, product.id
    finally:
        await engine.dispose()


async def _count_and_remove(dsn: str, user_id: int, product_id: UUID) -> int:
    engine = create_async_engine(dsn, poolclass=NullPool)
    try:
        async with engine.begin() as connection:
            pending = await connection.scalar(
                text("SELECT count(*) FROM purchases WHERE user_id = :u AND status = 'pending'"),
                {"u": user_id},
            )
            await connection.execute(
                text("DELETE FROM purchases WHERE user_id = :u"), {"u": user_id}
            )
            await connection.execute(text("DELETE FROM products WHERE id = :p"), {"p": product_id})
            await connection.execute(
                text("DELETE FROM users WHERE telegram_id = :u"), {"u": user_id}
            )
            return int(pending or 0)
    finally:
        await engine.dispose()


def test_0004_refuses_to_run_over_duplicate_pending_crypto_checkouts(
    migrated_database: str,
) -> None:
    """The index migration never resolves duplicates itself: it waits for them to expire."""
    config = alembic_config(migrated_database)
    command.downgrade(config, "0003")
    user_id, product_id = asyncio.run(_seed_duplicate_pending_checkouts(migrated_database))
    try:
        with pytest.raises(RuntimeError, match="more than one pending crypto purchase"):
            command.upgrade(config, "head")
    finally:
        # Nothing was rewritten by the refused upgrade: both rows are still pending.
        assert asyncio.run(_count_and_remove(migrated_database, user_id, product_id)) == 2
        command.upgrade(config, "head")
    command.check(config)
