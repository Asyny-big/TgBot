@pytest.mark.parametrize(
    ("seed", "reason"),
    [
        ((_INTERNAL_PURCHASE,), "internal purchase"),
        ((_LOYALTY_DISCOUNTED_PURCHASE,), "loyalty_amount"),
        ((_LOYALTY_DISCOUNTED_PURCHASE, _APPLIED_REWARD), "applied or consumed loyalty reward"),
        ((_INTERNAL_PURCHASE, _CONSUMED_REWARD), "applied or consumed loyalty reward"),
    ],
    ids=["internal-purchase", "loyalty-amount", "applied-reward", "consumed-reward"],
)
def test_0005_downgrade_refuses_while_history_depends_on_it(
    migrated_database: str,
    seed: tuple[str, ...],
    reason: str,
) -> None:
    """Refuse, and change nothing: the whole migration runs in one transaction."""
    config = alembic_config(migrated_database)
    _sql(
        migrated_database,
        *_SEED_BUYER_AND_PRODUCT,
        *seed,
        user_id=SEED_USER,
        slug="seedhistory",
    )
    try:
        with pytest.raises(RuntimeError, match=reason):
            command.downgrade(config, "0004")

        # One transaction: the refusal also undid the 0006 step before it.
        assert _version(migrated_database) == HEAD
        assert _provider_values(migrated_database) == ["stars", "crypto", "internal"]
        assert "ck_purchases_amount_matches_provider" in _purchase_checks(migrated_database)
        assert _scalar(migrated_database, "SELECT to_regclass('loyalty_rewards') IS NOT NULL")
        assert _index_definition(migrated_database, PENDING_CRYPTO_INDEX) is not None
        kept = _scalar(
            migrated_database,
            "SELECT count(*) FROM purchases WHERE user_id = :user_id",
            user_id=SEED_USER,
        )
        assert kept == sum(1 for statement in seed if "INTO purchases" in statement)
    finally:
        _remove_seed(migrated_database)
    command.check(config)


